const dicts: Record<Lang, Dict> = { en, fr };

function detect(): Lang {
  const saved = load<Lang | null>("21t:lang", null);
  if (saved === "en" || saved === "fr") return saved;
  return navigator.language?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>((set) => ({
  lang: detect(),
  setLang: (lang) => {
    save("21t:lang", lang);
    document.documentElement.lang = lang;
    set({ lang });
  },
}));

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useLang((s) => s.lang);
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function hasKey(key: string): key is TKey {
  return key in en;
}

export function fmt(n: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "fr" ? "fr-CA" : "en-CA").format(n);
}
